#!/usr/bin/env python3
"""ASCII mission map -> compressed tile id bytes.

Usage: map2asm.py <map.txt> <label> <out.asm>

One character per 8x8 tile, 40 columns x 32 rows. Multi-tile stamps are
written as their letter at the top-left corner with '+' filling the rest
of the footprint, so the text stays aligned with the grid.

Snow specks and shading (',' ':') are plain snow here: map_unpack
(src/game.asm) scatters them over the snow when the map loads, so they
don't break up the runs the compressor relies on.

Compressed format (map_unpack decodes it straight into map_buf):
  t = &00-&7F         t+1 literal tile bytes follow
  t = &80-&FF, lo, hi copy (t-&80)+MIN_MATCH bytes from lo+256*hi bytes back
The stream ends after MAP_W*MAP_H output bytes.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tiles_def import TILE_NAMES  # noqa: E402

MAP_W, MAP_H = 40, 32
MIN_MATCH, MAX_MATCH, MAX_LIT = 4, 127 + 4, 128


def compress(data):
    """Greedy LZ: the longest earlier match (min MIN_MATCH), else literals."""
    out, lits, i = [], [], 0

    def flush():
        while lits:
            chunk = lits[:MAX_LIT]
            del lits[:MAX_LIT]
            out.extend([len(chunk) - 1] + chunk)

    while i < len(data):
        best, dist = 0, 0
        for k in range(i - 1, -1, -1):
            n = 0
            while i + n < len(data) and n < MAX_MATCH and data[k + n] == data[i + n]:
                n += 1
            if n > best:
                best, dist = n, i - k
        if best >= MIN_MATCH:
            flush()
            out.extend([0x80 + best - MIN_MATCH, dist & 0xFF, dist >> 8])
            i += best
        else:
            lits.append(data[i])
            i += 1
    flush()
    return out


def decompress(packed, size):
    out, i = [], 0
    while len(out) < size:
        t = packed[i]
        if t < 0x80:
            out.extend(packed[i + 1:i + 2 + t])
            i += 2 + t
        else:
            dist = packed[i + 1] | packed[i + 2] << 8
            for _ in range(t - 0x80 + MIN_MATCH):
                out.append(out[-dist])
            i += 3
    return out

LEGEND = {
    ".": "snow", ",": "snow", ":": "snow", "=": "road", "i": "ice",
    "~": "water", "n": "bank_n", "u": "bank_s", "R": "rock", "-": "fence_h",
    "|": "fence_v", "W": "wall", "r": "roof", "e": "roof_edge", "D": "door",
    "b": "bridge", "s": "sandbag", "t": "tracks", "x": "rubble", "G": "gate",
    "#": "scorch", "[": "rail_l", "]": "rail_r", "_": "rail_h",
}
STAMPS = {"P": ("pine", 2, 3), "X": ("tower", 2, 4), "K": ("truck", 3, 2), "F": ("depot", 3, 2),
          "U": ("uboat", 16, 6), "Y": ("rbridge", 4, 3),
          "C": ("gun", 4, 3), "H": ("plant", 4, 3),
          "T": ("train", 10, 3)}


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    src, label, out = sys.argv[1:]
    rows = [r.rstrip("\n") for r in open(src) if r.strip()]
    if len(rows) != MAP_H or any(len(r) != MAP_W for r in rows):
        sys.exit(f"{src}: map must be {MAP_W}x{MAP_H}")
    ids = [[None] * MAP_W for _ in range(MAP_H)]
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in STAMPS:
                name, w, h = STAMPS[ch]
                for dy in range(h):
                    for dx in range(w):
                        if rows[y + dy][x + dx] not in (ch, "+") or (dx or dy) and rows[y + dy][x + dx] != "+":
                            sys.exit(f"{src}: stamp {ch} at {x},{y} needs '+' at {x + dx},{y + dy}")
                        ids[y + dy][x + dx] = TILE_NAMES.index(f"{name}{dy * w + dx}")
            elif ch in LEGEND:
                ids[y][x] = TILE_NAMES.index(LEGEND[ch])
            elif ch != "+":
                sys.exit(f"{src}: unknown map character {ch!r} at {x},{y}")
    for y in range(MAP_H):
        for x in range(MAP_W):
            if ids[y][x] is None:
                sys.exit(f"{src}: stray '+' at {x},{y}")
    flat = [t for row in ids for t in row]
    packed = compress(flat)
    assert decompress(packed, len(flat)) == flat
    with open(out, "w") as f:
        f.write(f"; Generated by tools/map2asm.py from {src} - do not edit\n"
                f"; {len(flat)} tiles packed into {len(packed)} bytes (format: tools/map2asm.py)\n"
                f"{label}:\n")
        for k in range(0, len(packed), 32):
            f.write("  db " + ",".join(str(b) for b in packed[k:k + 32]) + "\n")
    print(f"map2asm: {src} -> {out} ({len(packed)} bytes)")


if __name__ == "__main__":
    main()
