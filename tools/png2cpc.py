#!/usr/bin/env python3
"""PNG -> Amstrad CPC Mode 0 converter.

Usage:
    png2cpc.py <dir-with-manifest.json> <out.asm>

The manifest lists the sheets to convert:

    {"sheets": [
        {"file": "commando.png", "label": "spr_beret", "cell": [12, 16], "kind": "masked"},
        {"file": "tiles.png",    "label": "tiles",     "cell": [8, 8],   "kind": "plain"},
        {"file": "font.png",     "label": "font",      "cell": [4, 8],   "kind": "font"}
    ]}

kinds:
  plain   2 pixels per byte, row-major, transparent key -> pen 0
  masked  (mask, pixels) byte pairs, row-major. Mask bits are 1 where the
          screen shows through, so the blitter does (screen AND mask) OR pixels.
  font    1 bit per pixel, one byte per row, value 0..15 with bit 3 = leftmost
          pixel; any non-transparent, non-black pixel is "ink".

Cells are sliced left-to-right, top-to-bottom. Each cell gets a label
<label>_<n>, plus <label>_count and <label>_size equates.

Every opaque pixel must be an exact in-game palette colour (see
cpcpal.GAME_RGB); transparent pixels (alpha) or the magenta key #FF00FF
are transparent. Indexed PNGs exported by Aseprite work as they are.
"""
import json
import os
import sys

from PIL import Image

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cpcpal import GAME_RGB, TRANSPARENT, mode0_byte  # noqa: E402

RGB_TO_PEN = {rgb: i for i, rgb in enumerate(GAME_RGB)}


def pen_at(img, x, y, path):
    r, g, b, a = img.getpixel((x, y))
    rgb = (r, g, b)
    if a < 128 or rgb == TRANSPARENT:
        return None
    try:
        return RGB_TO_PEN[rgb]
    except KeyError:
        sys.exit(f"{path}: pixel ({x},{y}) colour {rgb} is not in the game palette")


def encode_cell(img, ox, oy, w, h, kind, path):
    out = []
    for y in range(oy, oy + h):
        if kind == "font":
            v = 0
            for i in range(4):
                p = pen_at(img, ox + i, y, path)
                if p not in (None, 0):
                    v |= 8 >> i
            out.append(v)
            continue
        for x in range(ox, ox + w, 2):
            p0 = pen_at(img, x, y, path)
            p1 = pen_at(img, x + 1, y, path)
            pix = mode0_byte(p0 or 0, p1 or 0)
            if kind == "masked":
                mask = (0xAA if p0 is None else 0) | (0x55 if p1 is None else 0)
                out += [mask, pix]
            else:
                out.append(pix)
    return out


def convert_sheet(src_dir, sheet):
    path = os.path.join(src_dir, sheet["file"])
    img = Image.open(path).convert("RGBA")
    w, h = sheet["cell"]
    kind = sheet.get("kind", "plain")
    if kind != "font" and w % 2:
        sys.exit(f"{path}: Mode 0 cell width must be even")
    if img.width % w or img.height % h:
        sys.exit(f"{path}: {img.width}x{img.height} is not a multiple of the {w}x{h} cell")
    cells = []
    for cy in range(0, img.height, h):
        for cx in range(0, img.width, w):
            cells.append(encode_cell(img, cx, cy, w, h, kind, path))
    count = sheet.get("count", len(cells))
    return cells[:count]


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src_dir, out_path = sys.argv[1], sys.argv[2]
    with open(os.path.join(src_dir, "manifest.json")) as f:
        manifest = json.load(f)
    lines = [f"; Generated by tools/png2cpc.py from {src_dir} - do not edit", ""]
    total = 0
    for sheet in manifest["sheets"]:
        label = sheet["label"]
        cells = convert_sheet(src_dir, sheet)
        size = len(cells[0])
        lines.append(f"{label}_count equ {len(cells)}")
        lines.append(f"{label}_size equ {size}")
        lines.append(f"{label}:")
        for n, cell in enumerate(cells):
            lines.append(f"{label}_{n}:")
            for i in range(0, len(cell), 16):
                lines.append("  db " + ",".join(f"&{b:02X}" for b in cell[i:i + 16]))
        lines.append("")
        total += size * len(cells)
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    with open(out_path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"png2cpc: {src_dir} -> {out_path} ({total} bytes)")


if __name__ == "__main__":
    main()
