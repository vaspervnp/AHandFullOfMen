#!/usr/bin/env python3
"""Convert text songs (assets/music/*.txt) to data for src/audio/music.asm.

Usage: music2asm.py out.asm song.txt...

Song file: `song <name>`, `tempo <ticks per row>`, `vol <A> <B>` (start
volumes), optional `loop`, then rows for the two voices on lines starting
with `A:` / `B:`. A row token is a note (c4, f#3 ...: octave 4 holds A440),
`.` to hold, `-` to rest; `|` is ignored. Output per song:
  song_<name>: dw voice_a, voice_b : db vol_a, vol_b
  voices: (note, ticks) pairs; note 0 = rest, 1.. = index into
  music_periods; then &FF (loop to the voice start) or &FE (stop).
Plus the shared AY tone-period table music_periods (1 MHz clock).
"""
import sys

NAMES = {"c": 0, "d": 2, "e": 4, "f": 5, "g": 7, "a": 9, "b": 11}
LOWEST = 2 * 12                  # c1 (MIDI 24) is note index 1


def midi(tok):
    n = NAMES[tok[0]]
    rest = tok[1:]
    if rest.startswith("#"):
        n += 1
        rest = rest[1:]
    return (int(rest) + 1) * 12 + n


def period(m):
    f = 440.0 * 2 ** ((m - 69) / 12)
    return min(4095, round(1_000_000 / (16 * f)))


def parse(path):
    song = {"tempo": 3, "vol": (12, 10), "loop": False, "A": [], "B": []}
    for line in open(path):
        line = line.split("#", 1)[0].strip() if not line.lstrip().startswith(("A:", "B:")) \
            else line.strip()
        if not line:
            continue
        if line[:2] in ("A:", "B:"):
            song[line[0]] += [t for t in line[2:].replace("|", " ").split()]
            continue
        word, *args = line.split()
        if word == "song":
            song["name"] = args[0]
        elif word == "tempo":
            song["tempo"] = int(args[0])
        elif word == "vol":
            song["vol"] = (int(args[0]), int(args[1]))
        elif word == "loop":
            song["loop"] = True
    if len(song["A"]) != len(song["B"]):
        sys.exit(f"{path}: voice A has {len(song['A'])} rows, B has {len(song['B'])}")
    return song


def events(rows, tempo, path):
    out = []
    for tok in rows:
        if tok == ".":
            if not out:
                sys.exit(f"{path}: a voice can't start with '.'")
            out[-1][1] += tempo
        elif tok == "-":
            out.append([0, tempo])
        else:
            idx = midi(tok) - LOWEST + 1
            if not 1 <= idx <= 96:
                sys.exit(f"{path}: note {tok} out of range")
            out.append([idx, tempo])
    data = []
    for note, ticks in out:
        while ticks > 255:             # long notes: re-trigger
            data += [note, 255]
            ticks -= 255
        data += [note, ticks]
    return data


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    lines = ["; generated by tools/music2asm.py - do not edit", "music_periods:"]
    for i in range(0, 96, 8):
        lines.append("  dw " + ",".join(str(period(LOWEST + j)) for j in range(i, i + 8)))
    for path in sys.argv[2:]:
        s = parse(path)
        n = s["name"]
        end = "&FF" if s["loop"] else "&FE"
        lines.append(f"song_{n}: dw song_{n}_a, song_{n}_b : db {s['vol'][0]}, {s['vol'][1]}")
        for v in "AB":
            data = events(s[v], s["tempo"], path)
            lines.append(f"song_{n}_{v.lower()}:")
            for i in range(0, len(data), 16):
                lines.append("  db " + ",".join(map(str, data[i:i + 16])))
            lines.append(f"  db {end}")
    open(sys.argv[1], "w").write("\n".join(lines) + "\n")
    print(f"music2asm: {len(sys.argv) - 2} songs -> {sys.argv[1]}")


if __name__ == "__main__":
    main()
